package subject;

// 자바 변수
public class JavaVariables {
    public static void main(String[] agrs) {

        // 변수 선언
        // 변수의 데이터 타입 + 변수 이름 + 대입 연산자(=) 를 사용하여 값을 할당
        // byte, short, int, long, float, double, char, boolean 타입의 경우
        // 스택메모리에 변수명과 할당된 값이 함께 저장됨
        int num1 = 0;
        float num2 = 1.223f;
        char ch = 'A';

        System.out.println(num1);
        System.out.println(num2);
        System.out.println(ch);

    }
}
